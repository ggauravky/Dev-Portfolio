/** Generate command items for every project in projectsData */
export const getProjectCommands = () => {
    return projectsData.map((project) => {
        const techList = project.techStack ? project.techStack.join(', ') : ''
        const cats = project.categories ? project.categories.join(', ') : ''
        const techKeywords = project.techStack
            ? project.techStack.map((t) => t.toLowerCase())
            : []
        return {
            id: `project-${project.slug}`,
            title: project.title,
            category: CATEGORIES.PROJECTS,
            desc: project.description
                ? project.description.slice(0, 100) + (project.description.length > 100 ? '…' : '')
                : `Engineering case study for ${project.title}`,
            type: 'internal',
            url: `/projects/${project.slug}`,
            badge: 'Case Study',
            priority: project.featured ? 75 : 55,
            aliases: [project.slug.replace(/-/g, ' ')],
            keywords: [
                project.title.toLowerCase(),
                project.slug.toLowerCase(),
                project.slug.replace(/-/g, ' '),
                'project',
                'case study',
                'demo',
                ...techKeywords,
                ...cats.toLowerCase().split(/[\s,]+/).filter(Boolean),
            ],
            // Expose techStack for display subtitles
            _techStack: project.techStack || [],
        }
    })
}

